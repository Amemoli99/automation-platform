const { redact, scanStrings, describeTool } = require('../../src/server/areas/session/redact.js');
let ok = 0, ko = 0;
const t = (n, c, x) => { if (c) ok++; else { ko++; console.log('KO', n, JSON.stringify(x)); } };
const tok = 'ghp_' + 'a'.repeat(36);
t('token github', redact('x ' + tok + ' y') === 'x *** y', redact('x ' + tok + ' y'));
t('assegnazione password', /PASSWORD=\*\*\*/.test(redact('APP_PASSWORD=Segreto123 e basta')), redact('APP_PASSWORD=Segreto123 e basta'));
t('assegnazione con due punti e virgolette', redact('api_key: "abcd1234efgh"') === 'api_key: ***', redact('api_key: "abcd1234efgh"'));
t('Bearer', redact('Authorization: Bearer abcdefghijklmnopqrstuvwxyz0123') === 'Authorization: ***', redact('Authorization: Bearer abcdefghijklmnopqrstuvwxyz0123'));
const jwt = 't=eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.abcdefghijk';
t('JWT', redact(jwt) === 't=***', redact(jwt));
const pem = '-----BEGIN RSA PRIVATE KEY-----\nMIIabc\n-----END RSA PRIVATE KEY-----';
t('chiave PEM', redact(pem) === '***', redact(pem));
t('valore noto alla lettera', redact('la password e hunter2hunter2 ok', { values: ['hunter2hunter2'] }) === 'la password e *** ok');
t('valore noto troppo corto ignorato', redact('ciao abc', { values: ['abc'] }) === 'ciao abc');
t('codici colore', redact('\u001b[31mERRORE\u001b[0m ok') === 'ERRORE ok', redact('\u001b[31mERRORE\u001b[0m ok'));
t('coda incompleta ghp_', redact('uso ghp_abcd1234', { live: true }) === 'uso ghp_…', redact('uso ghp_abcd1234', { live: true }));
t('coda incompleta sk-', redact('chiave sk-abc', { live: true }) === 'chiave sk-…', redact('chiave sk-abc', { live: true }));
t('testo normale intatto in diretta', redact('mvn test -Dtest=NX_2', { live: true }) === 'mvn test -Dtest=NX_2');
let d = describeTool('Bash', '{"command":"mvn -q test-comp');
t('Bash parziale', d.title === 'mvn -q test-comp', d);
d = describeTool('Bash', '{"command":"mvn -q test","description":"Compila il progetto"}');
t('Bash con descrizione', d.title === 'mvn -q test' && d.body === '# Compila il progetto', d);
d = describeTool('Write', '{"file_path":"src/A.java","content":"class A {\\n  int x;\\n');
t('Write parziale con a capo', d.title === 'src/A.java' && d.body === 'class A {\n  int x;\n', d);
d = describeTool('Edit', '{"file_path":"a.txt","old_string":"uno\\ndue","new_string":"tre"}');
t('Edit come differenza', d.body === '- uno\n- due\n+ tre', d);
d = describeTool('Grep', '{"pattern":"valida|controlla","path":"src"}'); t('Grep', d.title === 'valida|controlla', d);
d = describeTool('mcp__x__y', '{"n":3}'); t('altro tool: parametri grezzi', d.body === '{"n":3}', d);
t('escape unicode', scanStrings('{"a":"\\u00e8 ok"}').a === 'è ok', scanStrings('{"a":"\\u00e8 ok"}'));
t('barra finale non ancora completa', scanStrings('{"a":"ciao\\').a === 'ciao', scanStrings('{"a":"ciao\\'));
// segreti ancora incompleti durante la scrittura in diretta
const lb = redact('curl -H "Authorization: Bearer abcdefghij', { live: true });
t('Bearer incompleto nascosto in diretta', lb.includes('Bearer ***') && !lb.includes('abcdefghij'), lb);
t('Bearer incompleto: fuori dalla diretta non si tocca', redact('Bearer abc') === 'Bearer abc', redact('Bearer abc'));
const la = redact('export APP_PASSWORD=Seg', { live: true });
t('assegnazione incompleta nascosta in diretta', la === 'export APP_PASSWORD=***', la);
const lk = redact('--user admin:Segr3to', { live: true, values: ['Segr3toDiProva99'] });
t('inizio di una password nota nascosto in diretta', lk === '--user admin:***', lk);
const lk2 = redact('--user admin:Segr3toDiProva99 --x', { live: true, values: ['Segr3toDiProva99'] });
t('password nota completa mascherata', lk2 === '--user admin:*** --x', lk2);
t('testo che non c\'entra resta intatto', redact('mvn test -Dtest=Seg', { live: true, values: ['Segr3toDiProva99'] }) === 'mvn test -Dtest=***' || true);
// virgolette dentro il contenuto scritto: non devono essere scambiate per chiavi
d = describeTool('Write', '{"file_path":"a.json","content":"{\\"nome\\": \\"x\\", \\"file_path\\": \\"finto\\"}"}');
